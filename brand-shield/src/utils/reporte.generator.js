/**
 * Genera el PDF del reporte mensual en memoria y lo retorna como Buffer
 */
const generarPDF = (negocio, datos, idioma = 'es') => {
  const t = TEXTOS[idioma] || TEXTOS.es;

  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 50, size: 'A4' });
    const chunks = [];

    doc.on('data', chunk => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    const { snapshots, alertas, resenas, periodo } = datos;
    const snapActual = snapshots?.[0];
    // El score 0-100 que el catálogo anuncia en los cuatro planes. Hasta el
    // 2026-08-25 solo existía dentro del panel, así que el informe que el dueño
    // archiva o le enseña a su socio no lo llevaba. Sale de `lib/score.js`, la
    // misma fórmula que la ficha: dos números distintos con el mismo nombre
    // serían peor que no ponerlo.
    const puntuacion = score.calcular(snapActual, resenas || []);
    const snapInicio = snapshots?.[snapshots.length - 1];
    const variacion = snapActual && snapInicio
      ? (snapActual.ratingActual - snapInicio.ratingActual).toFixed(2)
      : null;

    // ── Encabezado ─────────────────────────────────────────
    doc.rect(0, 0, doc.page.width, 80).fill(INK);
    doc.rect(0, 80, doc.page.width, 3).fill(VERDE);
    doc.fillColor('#ffffff').fontSize(22).font('Times-Bold')
      .text('Notoria', 50, 25);
    doc.fontSize(11).font('Times-Roman').fillColor('#B0AEA5')
      .text(t.subtitulo, 50, 52);

    doc.moveDown(3);

    // ── Nombre del negocio ────────────────────────────────
    doc.fillColor(INK).fontSize(18).font('Times-Bold')
      .text(negocio.nombre, 50, 105);
    doc.fontSize(11).font('Times-Roman').fillColor(GRIS)
      .text(t.periodo(periodo, t.tipos[negocio.tipo] || negocio.tipo), 50, 130);

    doc.moveTo(50, 150).lineTo(545, 150).strokeColor(BORDE).stroke();

    // ── Métricas principales ──────────────────────────────
    doc.fontSize(14).font('Times-Bold').fillColor(INK)
      .text(t.resumen, 50, 165);

    const metricas = [
      { label: t.ratingActual, valor: snapActual ? `${snapActual.ratingActual} / 5` : t.sinDatos },
      { label: t.variacionMes, valor: variacion ? `${variacion > 0 ? '+' : ''}${variacion}` : '—' },
      { label: t.totalResenas, valor: snapActual?.totalResenas?.toLocaleString() || '—' },
      // `null` cuando no hay snapshot: un negocio recién conectado no tiene
      // «cero reputación», tiene «todavía no medimos». Un 0 en un informe
      // impreso es una acusación.
      { label: t.score, valor: puntuacion ? `${puntuacion.score} / 100` : t.sinDatos },
      { label: t.alertasMes, valor: String(alertas?.length || 0) },
      { label: t.resenasSospechosas, valor: String(resenas?.filter(r => r.esSospechosa)?.length || 0) },
    ];

    let yPos = 190;
    metricas.forEach((m, i) => {
      const x = i % 2 === 0 ? 50 : 300;
      if (i % 2 === 0 && i > 0) yPos += 55;

      doc.rect(x, yPos, 230, 45).fillAndStroke(FONDO, BORDE);
      doc.fontSize(10).font('Times-Roman').fillColor(GRIS)
        .text(m.label, x + 10, yPos + 8);
      doc.fontSize(16).font('Times-Bold').fillColor(INK)
        .text(m.valor, x + 10, yPos + 22);
    });

    yPos += 70;

    // ── Alertas del período ───────────────────────────────
    if (alertas?.length > 0) {
      doc.fontSize(14).font('Times-Bold').fillColor(INK)
        .text(t.alertasDetectadas, 50, yPos);
      yPos += 25;

      alertas.slice(0, 5).forEach(a => {
        doc.fontSize(10).font('Times-Roman').fillColor(GRIS)
          .text(`• ${a.descripcion}`, 50, yPos, { width: 495 });
        yPos += doc.heightOfString(a.descripcion, { width: 495 }) + 8;
      });
    }

    // ── Recomendaciones ───────────────────────────────────
    yPos += 10;
    doc.fontSize(14).font('Times-Bold').fillColor(INK)
      .text(t.recomendaciones, 50, yPos);
    yPos += 25;

    const recomendaciones = [];
    if (snapActual?.ratingActual < 4.0) {
      recomendaciones.push(t.recRatingBajo);
    }
    if (snapActual?.totalResenas < 50) {
      recomendaciones.push(t.recPocasResenas);
    }
    if ((resenas?.filter(r => r.esSospechosa)?.length || 0) >= 2) {
      recomendaciones.push(t.recSospechosas);
    }
    if (recomendaciones.length === 0) {
      recomendaciones.push(t.recExcelente);
    }

    recomendaciones.forEach(r => {
      doc.fontSize(10).font('Times-Roman').fillColor(GRIS)
        .text(`— ${r}`, 50, yPos, { width: 495 });
      yPos += doc.heightOfString(r, { width: 495 }) + 10;
    });

    // ── Footer ────────────────────────────────────────────
    doc.fontSize(9).font('Times-Roman').fillColor(GRIS_CLARO)
      .text(
        t.footer(new Date().toLocaleDateString(t.localeFecha)),
        50, doc.page.height - 40, { align: 'center', width: 495 }
      );

    doc.end();
  });
};

/**
 * Genera y envía el reporte PDF por email al usuario
 */
const enviarReporteMensual = async (usuario, negocio, datos) => {
  const idioma = usuario.idioma === 'en' ? 'en' : 'es';
  const t = TEXTOS[idioma];

  try {
    const mesActual = new Date().toLocaleDateString(t.localeFecha, { month: 'long', year: 'numeric' });
    const periodo = mesActual.charAt(0).toUpperCase() + mesActual.slice(1);

    const pdfBuffer = await generarPDF(negocio, { ...datos, periodo }, idioma);

    const resend = getResend();
    await resend.emails.send({
      from: FROM(),
      to: usuario.email,
      subject: t.email.asunto(negocio.nombre, periodo),
      html: base(`
        ${h1(t.email.titulo(periodo))}
        ${p(t.email.saludo(usuario.nombre))}
        ${p(t.email.cuerpo(negocio.nombre, periodo))}
        ${p(t.email.detalle)}
      `),
      attachments: [{
        filename: `reporte-${negocio.nombre.toLowerCase().replace(/\s+/g, '-')}-${periodo.toLowerCase()}.pdf`,
        content: pdfBuffer.toString('base64'),
      }],
    });

    console.log(`[Reporte] PDF enviado a ${usuario.email} para ${negocio.nombre}`);
    return true;
  } catch (error) {
    console.error(`[Reporte] Error generando/enviando PDF: ${error.message}`);
    return false;
  }
};

module.exports = { generarPDF, enviarReporteMensual };
